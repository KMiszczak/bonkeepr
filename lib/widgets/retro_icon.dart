  @override
  Widget build(BuildContext context) {
    if (!ThemeController.instance.isRetroMode) {
      return Icon(icon, color: color, size: size, semanticLabel: semanticLabel);
    }
    final glyph = CustomPaint(
      size: Size.square(size),
      painter: _PixelGlyphPainter(
        _glyphs[icon] ??
            const [
              '1111111',
              '1000001',
              '1011101',
              '1010101',
              '1011101',
              '1000001',
              '1111111',
            ],
        color ?? Theme.of(context).colorScheme.primary,
      ),
    );
    if (semanticLabel == null) return glyph;
    return Semantics(label: semanticLabel, image: true, child: glyph);
  }
}

class _PixelGlyphPainter extends CustomPainter {
  const _PixelGlyphPainter(this.rows, this.color);

  final List<String> rows;
  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    final cellWidth = size.width / rows.first.length;
    final cellHeight = size.height / rows.length;
    final paint = Paint()
      ..color = color
      ..isAntiAlias = false;
    for (var row = 0; row < rows.length; row++) {
      for (var column = 0; column < rows[row].length; column++) {
        if (rows[row][column] == '1') {
          canvas.drawRect(
            Rect.fromLTWH(
              column * cellWidth,
              row * cellHeight,
              cellWidth,
              cellHeight,
            ),
            paint,
          );
        }
      }
    }
  }

  @override
  bool shouldRepaint(covariant _PixelGlyphPainter oldDelegate) =>
      oldDelegate.rows != rows || oldDelegate.color != color;
}
